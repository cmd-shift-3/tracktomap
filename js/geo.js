// geo.js — простая локальная проекция lat/lon в метры (плоская земля).
// Для масштабов ориентирования (км, не сотни км) этого достаточно и
// не тянет за собой библиотеки/тайлы карт.

const EARTH_RADIUS_M = 6371000;

/**
 * Создаёт проекцию с origin в первой точке трека.
 * x растёт на восток (вправо — как и пиксели изображения), y растёт на юг
 * (вниз — как и пиксели изображения, где ось Y направлена вниз).
 *
 * Важно: y намеренно инвертирован относительно "географического" севера.
 * Калибровочная модель (transform.js) — это подобие (поворот+масштаб+сдвиг),
 * без отражения. Если бы здесь y рос на север (вверх), а координаты на
 * карте (target) росли бы вниз, то верное соответствие между ними было бы
 * зеркальным (отражением), а не поворотом — и подобие не смогло бы его
 * корректно описать: 2 опорные точки совпадали бы точно, но весь трек
 * между ними и за их пределами оказывался бы зеркально перевёрнут
 * (например, шёл влево вместо вправо). Приведя оси source и target к
 * одинаковой ориентации (обе "вниз"/"на юг" по Y) с самого начала, любое
 * реальное соответствие между треком и картой становится чистым
 * поворотом+масштабом+сдвигом — и подобие описывает его точно.
 */
function makeProjection(originLat, originLon) {
  const cosLat0 = Math.cos((originLat * Math.PI) / 180);
  return {
    originLat,
    originLon,
    toMeters(lat, lon) {
      const x =
        EARTH_RADIUS_M * ((lon - originLon) * Math.PI) / 180 * cosLat0;
      const y = -EARTH_RADIUS_M * ((lat - originLat) * Math.PI) / 180;
      return { x, y };
    },
  };
}

/** Расстояние между двумя точками lat/lon по формуле гаверсинуса (метры). */
function haversineDistance(lat1, lon1, lat2, lon2) {
  const toRad = (d) => (d * Math.PI) / 180;
  const dLat = toRad(lat2 - lat1);
  const dLon = toRad(lon2 - lon1);
  const a =
    Math.sin(dLat / 2) ** 2 +
    Math.cos(toRad(lat1)) * Math.cos(toRad(lat2)) * Math.sin(dLon / 2) ** 2;
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return EARTH_RADIUS_M * c;
}
